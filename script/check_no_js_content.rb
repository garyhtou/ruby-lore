#!/usr/bin/env ruby
# frozen_string_literal: true

# The zero-JS-content guard. Run after a build with:
#   bin/bridgetown build && ruby script/check_no_js_content.rb
# (Precondition: this script inspects an existing output/ directory; it
# does not build the site itself. That mirrors how a CI job would call
# it - a `bin/bridgetown build` step first, then this check - and keeps
# the script's own job narrow. It errors clearly if output/ is missing.)
#
# This is the tripwire for the site's one hard rule: the content layer
# (every card's facts, prose, and cross-links) must be real static HTML
# that works with JavaScript OFF. The future (Phase 2b) GSAP experience
# layer may only animate/reveal DOM that already exists - it may never
# be the only place a fact or link lives.
#
# For every card, this loads its built output/<segment>/<slug>/index.html,
# strips out every <script>...</script> block, and asserts that two kinds
# of signal survive the strip:
#   - a content-bearing text signal from EVERY substantial paragraph of
#     the card's body - not just the first one. (An earlier version of
#     this check only verified the first paragraph; a code review for
#     this task caught that moving a *later*, link-free paragraph into a
#     script slipped past undetected. Phase 2b is about to add per-
#     paragraph scroll/animation islands, so partial regressions like
#     that are a realistic thing to guard against, not just a whole-body
#     wipe.)
#   - every cross-link href the card's body points at via a [[slug]]
#     token, anywhere in the body
#
# If either check fails once scripts are removed, that content was only
# reachable via a script - BLOCK. Right now there is no JS content
# injection at all, so this passes trivially; its job is to catch a
# future regression where someone moves body content into a script.
#
# How each paragraph's expected text is derived: rather than hand-
# modeling kramdown's markdown->HTML rules with regexes (emphasis
# markers, list/blockquote markers, wikilink resolution, smart-quote
# typography, GFM's underscore-in-word handling, ...) - which is exactly
# the class of bug an earlier version of this script had (see git log for
# task 2.4) - each paragraph is rendered through the SAME Kramdown engine,
# with the SAME options, that the real Bridgetown build uses (see
# KRAMDOWN_OPTIONS below, copied from bridgetown-core's defaults; this
# site doesn't override any of them in bridgetown.config.yml). That
# sidesteps re-modeling kramdown's rendering rules and guarantees the
# "expected" text is generated by the real renderer, not an approximation
# of it. `[[slug]]` tokens are pre-resolved to the same
# `<a href="...">Title</a>` HTML the WikiLinks builder produces
# (plugins/wiki_links.rb + src/_components/card_link.erb) before handing
# the paragraph to Kramdown, since Kramdown itself only sees post-
# wikilink-resolution content in the real build too.
#
# All cards are checked and all problems are reported together, matching
# script/validate.rb's style.

require "kramdown"
require "cgi"
require_relative "../lib/slugs"

OUTPUT_DIR = File.expand_path("../output", __dir__)

# Copied from bridgetown-core's default `kramdown` config (see
# bridgetown-core/lib/bridgetown-core/configuration.rb). This site's
# bridgetown.config.yml doesn't set a `kramdown:` key, so these defaults
# are exactly what the real build uses.
KRAMDOWN_OPTIONS = {
  "auto_ids" => true,
  "toc_levels" => (1..6).to_a,
  "entity_output" => "as_char",
  "smart_quotes" => "lsquo,rsquo,ldquo,rdquo",
  "input" => "GFM",
  "hard_wrap" => false,
  "guess_lang" => true,
  "footnote_nr" => 1,
  "show_warnings" => false,
  "include_extraction_tags" => false,
  "mark_highlighting" => true
}.freeze

WIKILINK_PATTERN = /\[\[([a-zA-Z0-9_-]+)\]\]/
SOURCES_HEADING_PATTERN = /^##\s+Sources\s*$/i
SCRIPT_TAG_PATTERN = /<script\b[^>]*>.*?<\/script>/mi
HTML_TAG_PATTERN = /<[^>]+>/
# Straight and "smart"/typographic quote characters. Kramdown's smart
# typography rewrites straight quotes/apostrophes in the source markdown
# into curly Unicode quotes in the rendered HTML (e.g. "it's" -> "it's").
# Stripping every variant of these from both sides before comparing means
# that cosmetic typographic conversion is never mistaken for missing
# content.
QUOTE_CHARS_PATTERN = /['"‘’“”`]/
# Kramdown also collapses a literal "..." into a single Unicode ellipsis
# character in rendered output; normalize both to the same thing so that
# gets treated the same as the quote-typography case above.
ELLIPSIS_PATTERN = /\.\.\.|…/
MIN_SIGNAL_WORDS = 8

unless Dir.exist?(OUTPUT_DIR)
  warn "check_no_js_content.rb: no output/ directory found at #{OUTPUT_DIR}."
  warn "  This check inspects a built site; it does not build one. Run `bin/bridgetown build` first."
  exit 1
end

def strip_scripts(html)
  html.gsub(SCRIPT_TAG_PATTERN, "")
end

def decode_entities(text)
  text.gsub("&amp;", "&").gsub("&lt;", "<").gsub("&gt;", ">")
    .gsub("&quot;", '"').gsub(/&#0?39;/, "'").gsub("&nbsp;", " ")
end

def html_to_text(html)
  decode_entities(html.gsub(HTML_TAG_PATTERN, "")).gsub(/\s+/, " ").strip
end

def normalize(text)
  text.gsub(QUOTE_CHARS_PATTERN, "").gsub(ELLIPSIS_PATTERN, "...").gsub(/\s+/, " ").strip
end

# The card's body, as markdown, with the "## Sources" section (and
# everything after it) dropped - sources citations aren't the kind of
# "fact/card/link" content this check is protecting.
def prose_body(body)
  lines = body.to_s.lines
  heading_index = lines.index { |line| line.match?(SOURCES_HEADING_PATTERN) }
  (heading_index ? lines[0...heading_index] : lines).join
end

# Splits on blank lines, matching how kramdown itself delimits blocks
# (paragraphs, list blocks, blockquotes, headings).
def prose_paragraphs(body)
  prose_body(body).split(/\n\s*\n/).map(&:strip).reject(&:empty?)
end

# Replaces `[[slug]]` tokens with the same `<a href="...">Title</a>` HTML
# plugins/wiki_links.rb + src/_components/card_link.erb render, so
# Kramdown sees exactly what it sees in the real build. `CGI.escapeHTML`
# matches Erubi's `h()` escaping that card_link.erb's `<%= @title %>`
# applies (both escape & < > " '). An unresolved slug is left as literal
# `[[slug]]` text - that's script/validate.rb's problem, not this
# check's, and Kramdown will just render it as plain text.
def resolve_wikilinks(markdown, cards)
  markdown.gsub(WIKILINK_PATTERN) do
    slug = Regexp.last_match(1)
    target = cards[slug]
    next Regexp.last_match(0) unless target&.href && target.title

    %(<a href="#{target.href}">#{CGI.escapeHTML(target.title.to_s)}</a>)
  end
end

def render_paragraph(markdown_paragraph, cards)
  Kramdown::Document.new(resolve_wikilinks(markdown_paragraph, cards), KRAMDOWN_OPTIONS).to_html
end

# One [raw_markdown, normalized_plain_text] pair per body paragraph
# substantial enough to be a reliable content signal (skips bare heading
# fragments and one-line asides, same MIN_SIGNAL_WORDS bar the original
# version of this check used - just applied to every paragraph now,
# instead of only the first).
def paragraph_signals(body, cards)
  prose_paragraphs(body).filter_map do |raw_paragraph|
    text = normalize(html_to_text(render_paragraph(raw_paragraph, cards)))
    next nil if text.split(/\s+/).size < MIN_SIGNAL_WORDS

    [raw_paragraph, text]
  end
end

cards = Slugs.load_cards
errors = []
checked = 0

cards.each_value do |card|
  location = card.path

  if card.error || card.href.nil?
    errors << "#{location}: skipped (card has a front-matter problem that script/validate.rb should catch)"
    next
  end

  output_path = File.join(OUTPUT_DIR, card.href.delete_prefix("/"), "index.html")
  relative_output_path = "output/#{card.href.delete_prefix("/")}index.html"

  unless File.exist?(output_path)
    errors << "#{card.slug}: expected built page at #{relative_output_path} but it doesn't exist (build may be stale)"
    next
  end

  checked += 1
  html = File.read(output_path)
  scriptless_html = strip_scripts(html)
  scriptless_text = normalize(html_to_text(scriptless_html))

  signals = paragraph_signals(card.body, cards)
  if signals.empty?
    errors << "#{card.slug}: could not find any body paragraph with #{MIN_SIGNAL_WORDS}+ words to use as a " \
              "content signal - the card body may be too thin for this check to verify"
  else
    signals.each do |raw_paragraph, text|
      next if scriptless_text.include?(text)

      excerpt = raw_paragraph.gsub(/\s+/, " ").strip
      excerpt = "#{excerpt[0, 80]}…" if excerpt.length > 80
      errors << "#{card.slug}: body paragraph is missing from #{relative_output_path} once <script> tags " \
                "are stripped - expected to find (a normalized form of) the paragraph starting #{excerpt.inspect}"
    end
  end

  card.body.to_s.scan(WIKILINK_PATTERN).flatten.uniq.each do |linked_slug|
    target = cards[linked_slug]
    next unless target&.href # an unresolved [[slug]] is validate.rb's problem, not this check's

    expected_href = %(href="#{target.href}")
    unless scriptless_html.include?(expected_href)
      errors << "#{card.slug}: cross-link to [[#{linked_slug}]] (#{expected_href}) is missing from " \
                "#{relative_output_path} once <script> tags are stripped"
    end
  end
end

if errors.empty?
  puts "#{checked} card page#{"s" unless checked == 1} checked, all body content and cross-links " \
       "survive with <script> tags stripped."
  exit 0
else
  warn "check_no_js_content.rb found #{errors.size} problem#{"s" unless errors.size == 1}:"
  errors.each { |message| warn "  - #{message}" }
  exit 1
end
